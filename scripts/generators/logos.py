def inline_logo_group(name: str, x: float, y: float, size: float = 18.0, fill: str | None = None) -> str:
    """Return an SVG <g> containing the named 24x24 logo positioned and scaled."""
    spec = LOGOS[name]
    scale = size / 24.0
    color = escape(fill or spec["color"])
    return (
        f'<g transform="translate({x:.1f}, {y:.1f}) scale({scale:.4f})" fill="{color}">'
        f'<path d="{spec["path"]}"/>'
        f"</g>"
    )


def render_standalone_logo_svg(name: str) -> str:
    """Render a crisp 38x38 dark-terminal logo button SVG for README icon links."""
    spec = LOGOS[name]
    title = escape(spec["title"])
    color = escape(spec["color"])
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 38 38" width="38" height="38" '
        f'role="img" aria-label="{title}">\n'
        f'  <title>{title}</title>\n'
        f'  <rect x="0.5" y="0.5" width="37" height="37" rx="6" fill="#0D1117" stroke="#30363D"/>\n'
        f'  <g transform="translate(9, 9) scale(0.8333)" fill="{color}">\n'
        f'    <path d="{spec["path"]}"/>\n'
        f'  </g>\n'
        f'</svg>\n'
    )


def write_logo_svgs(logos_dir: Path) -> None:
    """Write all standalone platform logo SVG files."""
    logos_dir.mkdir(parents=True, exist_ok=True)
    for name in LOGOS:
        (logos_dir / f"{name}.svg").write_text(render_standalone_logo_svg(name), encoding="utf-8")
